def set_fonts(style_or_run, east='宋体', ascii_font='Times New Roman',
              size=None, bold=None, color=None):
    font = style_or_run.font
    font.name = ascii_font
    rpr = style_or_run.element.get_or_add_rPr() if hasattr(style_or_run, 'element') else None
    el = style_or_run._element if hasattr(style_or_run, '_element') else None
    # 对 style 与 run 统一处理
    try:
        rPr = style_or_run.element.rPr
    except AttributeError:
        rPr = None
    if rPr is None:
        try:
            rPr = style_or_run._element.get_or_add_rPr()
        except Exception:
            rPr = None
    if rPr is not None:
        rFonts = rPr.find(qn('w:rFonts'))
        if rFonts is None:
            rFonts = rPr.makeelement(qn('w:rFonts'), {})
            rPr.append(rFonts)
        rFonts.set(qn('w:ascii'), ascii_font)
        rFonts.set(qn('w:hAnsi'), ascii_font)
        rFonts.set(qn('w:eastAsia'), east)
    if size is not None:
        font.size = Pt(size)
    if bold is not None:
        font.bold = bold
    if color is not None:
        font.color.rgb = RGBColor(*color)


