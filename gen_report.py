def P(text='', size=12, bold=False, align=None, indent=True, east='宋体',
      color=None, space_after=0):
    p = doc.add_paragraph()
    if align is not None:
        p.alignment = align
    if indent and align is None:
        p.paragraph_format.first_line_indent = Pt(size * 2)
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.line_spacing = 1.5
    r = p.add_run(text)
    set_fonts(r, east=east, size=size, bold=bold, color=color)
    return p


def H(level, text):
    h = doc.add_heading('', level=level)
    r = h.add_run(text)
    east = {1: '黑体', 2: '黑体', 3: '黑体', 4: '黑体'}[level]
    set_fonts(r, east=east, size={1: 16, 2: 14, 3: 12.5, 4: 12}[level],
              bold=True, color=(0, 0, 0))
    return h


def PIC(path, caption, width_cm=14.5):
    if not os.path.exists(path):
        P(f'【图片缺失：{os.path.basename(path)}】', align=WD_ALIGN_PARAGRAPH.CENTER, indent=False)
        return
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.add_run().add_picture(path, width=Cm(width_cm))
    cap = doc.add_paragraph()
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = cap.add_run(caption)
    set_fonts(r, east='宋体', size=10.5, bold=True)


def TABLE(headers, rows, caption=None, widths=None, size=10.5):
    if caption:
        cap = doc.add_paragraph()
        cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = cap.add_run(caption)
        set_fonts(r, east='宋体', size=10.5, bold=True)
    t = doc.add_table(rows=1 + len(rows), cols=len(headers))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, htext in enumerate(headers):
        cell = t.rows[0].cells[j]
        cell.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = cell.paragraphs[0].add_run(str(htext))
        set_fonts(r, east='黑体', size=size, bold=True)
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            cell = t.rows[i + 1].cells[j]
            r = cell.paragraphs[0].add_run(str(val))
            set_fonts(r, east='宋体', size=size)
    if widths:
        for j, w in enumerate(widths):
            for row in t.rows:
                row.cells[j].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


